// Scans diagrams/*.html and writes diagrams.js (window.DIAGRAMS = [...]).
// A .js file (not JSON) because pages opened via file:// cannot fetch local files.
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const dir = join(root, 'diagrams');

function decodeEntities(s) {
  return s
    .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'")
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(+n));
}

function readTitle(path) {
  // Only the head matters; read the first 64 KB to stay fast on large files.
  const text = readFileSync(path, 'utf8').slice(0, 65536);
  const m = text.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  const t = m ? decodeEntities(m[1]).replace(/\s+/g, ' ').trim() : '';
  return t || null;
}

function readMeta(name) {
  const p = join(dir, name.replace(/\.html?$/i, '') + '.meta.json');
  if (!existsSync(p)) return {};
  try {
    return JSON.parse(readFileSync(p, 'utf8').replace(/^﻿/, ''));
  } catch (e) {
    console.warn(`  ! could not parse ${basename(p)}: ${e.message}`);
    return {};
  }
}

const files = existsSync(dir)
  ? readdirSync(dir).filter((f) => /\.html?$/i.test(f))
  : [];

const diagrams = files.map((file) => {
  const full = join(dir, file);
  const st = statSync(full);
  const meta = readMeta(file);
  const order = Number.isFinite(meta.order) ? meta.order : null;
  return {
    file,
    path: 'diagrams/' + file,
    title: (typeof meta.title === 'string' && meta.title.trim()) || readTitle(full) || file.replace(/\.html?$/i, ''),
    description: typeof meta.description === 'string' ? meta.description : '',
    tags: Array.isArray(meta.tags) ? meta.tags.map(String) : [],
    // neutral (any app) | bonds (BondScanner) | ultra (TapInvest): tints the hub card.
    theme: ['neutral', 'bonds', 'ultra'].includes(meta.theme) ? meta.theme : 'neutral',
    // flow (a journey through our apps' code) | concept (general Android/Flutter idea): drives the hub filters.
    kind: meta.kind === 'concept' ? 'concept' : 'flow',
    order,
    modified: st.mtime.toISOString(),
    size: st.size,
  };
});

diagrams.sort((a, b) => {
  const ao = a.order ?? Infinity, bo = b.order ?? Infinity;
  if (ao !== bo) return ao - bo;
  return a.file.localeCompare(b.file, undefined, { numeric: true });
});

const out =
  '// Generated by build.mjs - do not edit by hand.\n' +
  `// Built ${new Date().toISOString()}\n` +
  'window.DIAGRAMS = ' + JSON.stringify(diagrams, null, 2) + ';\n';
writeFileSync(join(root, 'diagrams.js'), out);

console.log(`Diagram Hub: ${diagrams.length} diagram(s) written to diagrams.js`);
for (const d of diagrams) console.log(`  - ${d.file}: ${d.title}`);
